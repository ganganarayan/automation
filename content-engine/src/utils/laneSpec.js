/**
 * Lanes + stages: pure helpers.
 *
 * Purpose:      The settings-free pieces of the lane model — which lane an
 *               instance belongs to, which stage a ready-video instance is at,
 *               the transcript gate (approved transcript before any paid copy),
 *               SRT → plain text, and the Whisper glossary prompt.
 * Responsibility: Pure functions only (unit-tested without a database).
 * Dependencies: none.
 *
 * Ready-video stages: prepare (✂ Clean, optional) → transcript (gate: the
 * operator edits / pastes an SRT and approves) → AI copy + thumbnails →
 * review & schedule → posted.
 */

/** Where an instance's item came from. */
export const SOURCE_TYPES = {
  drive_folder: 'Drive folder',
  drive_pick: 'Picked from Drive',
  sheet: 'Google Sheet',
  generated: 'Generated by the app',
};

export const READY_STAGES = [
  { key: 'prepare', label: 'Prepare' },
  { key: 'transcript', label: 'Transcript' },
  { key: 'copy', label: 'AI copy + thumbnails' },
  { key: 'review', label: 'Review & schedule' },
  { key: 'posted', label: 'Posted' },
];

/** Instance status while a transcript waits for the operator's approval. */
export const TRANSCRIPT_REVIEW = 'transcript_review';

const stepOf = (steps, key) => (Array.isArray(steps) ? steps : []).find((s) => s && s.key === key) || null;
const artOf = (steps, key) => (stepOf(steps, key) || {}).artifacts || {};

/**
 * The lane an instance runs in: 'ready' (a finished video from Drive),
 * 'generated' (hand-stepped pipeline run) or 'pipeline' (the automated daily run).
 */
export function laneOf(row = {}) {
  const t = row.source_type || '';
  if (t === 'drive_folder' || t === 'drive_pick') return 'ready';
  if (t === 'generated' || row.status === 'manual') return 'generated';
  if (row.status === 'draft' || row.status === TRANSCRIPT_REVIEW) return 'ready';
  return 'pipeline';
}

/** True once the operator approved this instance's transcript. */
export function transcriptApproved(steps) {
  return !!artOf(steps, 'transcript').approvedAt;
}

/** The paid copy + thumbnail step may run only after the transcript gate. */
export function canGenerateCopy(steps) {
  return transcriptApproved(steps);
}

/** The ready-video stage an instance is at (see READY_STAGES). */
export function readyStage(row = {}, steps = []) {
  if (row.status === 'posted' || row.locked) return 'posted';
  if (artOf(steps, 'script').copy) return 'review';
  if (transcriptApproved(steps)) return 'copy';
  const t = stepOf(steps, 'transcript');
  if (row.status === TRANSCRIPT_REVIEW || (t && t.status === 'done')) return 'transcript';
  return 'prepare';
}

export function stageLabel(key) {
  return (READY_STAGES.find((s) => s.key === key) || {}).label || key;
}

const TIMING = /^\s*(\d{1,2}:)?\d{1,2}:\d{2}([.,]\d{1,3})?\s*-->\s*(\d{1,2}:)?\d{1,2}:\d{2}([.,]\d{1,3})?.*$/;

/** Does this text look like an SRT / WebVTT subtitle file? */
export function isSrt(text) {
  return String(text || '').split(/\r?\n/).some((l) => TIMING.test(l));
}

/**
 * Subtitles → plain text for the LLM: drops the WEBVTT header, cue numbers,
 * timing lines and inline tags, and joins the cue text into one paragraph.
 * Plain text passes through (whitespace tidied).
 */
export function srtToText(raw) {
  const s = String(raw || '').replace(/^﻿/, '');
  if (!isSrt(s)) return s.replace(/\r\n/g, '\n').replace(/[ \t]+/g, ' ').replace(/\n{3,}/g, '\n\n').trim();
  const lines = s.split(/\r?\n/);
  const out = [];
  for (let i = 0; i < lines.length; i += 1) {
    const l = lines[i].trim();
    if (!l || /^WEBVTT\b/.test(l) || /^(NOTE|STYLE|REGION)\b/.test(l) || TIMING.test(l)) continue;
    // A cue number is a bare integer right before a timing line.
    if (/^\d+$/.test(l) && TIMING.test((lines[i + 1] || '').trim())) continue;
    out.push(l.replace(/<[^>]+>/g, '').replace(/\{\\[^}]*\}/g, '').trim());
  }
  return out.filter(Boolean).join(' ').replace(/\s+/g, ' ').trim();
}

/**
 * What the operator typed or pasted in the transcript box → { text, srt }:
 * `text` is what the LLM sees; `srt` keeps the raw subtitles (with timestamps)
 * for later captions, or '' when the input was plain text.
 */
export function prepareTranscript(input) {
  const raw = String(input || '').trim();
  return isSrt(raw) ? { text: srtToText(raw), srt: raw } : { text: srtToText(raw), srt: '' };
}

/** Glossary setting → unique terms (one per line or comma-separated). */
export function glossaryTerms(glossary) {
  const seen = new Set();
  const out = [];
  for (const t of String(glossary || '').split(/[\n,;]+/)) {
    const term = t.trim();
    if (!term || seen.has(term.toLowerCase())) continue;
    seen.add(term.toLowerCase());
    out.push(term);
  }
  return out;
}

/**
 * The Whisper `prompt` from the glossary, so names come out spelled right.
 * Whisper reads only the last ~224 tokens of a prompt, so it is capped.
 */
export function whisperPrompt(glossary, max = 800) {
  const terms = glossaryTerms(glossary);
  if (!terms.length) return '';
  let s = '';
  for (const t of terms) {
    const next = s ? `${s}, ${t}` : t;
    if (next.length + 1 > max) break;
    s = next;
  }
  return s ? `${s}.` : '';
}

export default {
  SOURCE_TYPES, READY_STAGES, TRANSCRIPT_REVIEW, laneOf, transcriptApproved, canGenerateCopy, readyStage, stageLabel,
  isSrt, srtToText, prepareTranscript, glossaryTerms, whisperPrompt,
};
